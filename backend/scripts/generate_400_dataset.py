def shuffle_options_realistically(records):
    # To make answers realistic (A, B, C, D distribution instead of all A)
    # distribute answers deterministically: 0->A, 1->B, 2->C, 3->D
    pattern = ["A", "B", "C", "D"]
    for i, rec in enumerate(records):
        target_ans = pattern[i % 4]
        if target_ans == "A":
            pass
        elif target_ans == "B":
            # swap A and B
            rec["option_a"], rec["option_b"] = rec["option_b"], rec["option_a"]
            rec["correct_answer"] = "B"
        elif target_ans == "C":
            # swap A and C
            rec["option_a"], rec["option_c"] = rec["option_c"], rec["option_a"]
            rec["correct_answer"] = "C"
        elif target_ans == "D":
            # swap A and D
            rec["option_a"], rec["option_d"] = rec["option_d"], rec["option_a"]
            rec["correct_answer"] = "D"
    return records

