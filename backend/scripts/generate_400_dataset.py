def validate_dataset(records):
    report = {
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "dataset_version": VERSION,
        "total_records_evaluated": len(records),
        "total_accepted": 0,
        "total_rejected": 0,
        "duplicates_found": 0,
        "incomplete_records": 0,
        "verified_records": 0,
        "subject_distribution": {},
        "difficulty_distribution": {},
        "answer_distribution": {},
        "validation_checks_passed": True,
        "errors": []
    }
    
    seen_ids = set()
    seen_texts = set()
    
    for r in records:
        errs = []
        # ID check
        if not r.get("question_id"):
            errs.append("Missing question_id")
        elif r["question_id"] in seen_ids:
            errs.append(f"Duplicate question_id: {r['question_id']}")
        seen_ids.add(r["question_id"])
        
        # Text and duplicate check
        norm_text = re.sub(r'\s+', ' ', r.get("question_text", "")).strip().lower()
        if not norm_text:
            errs.append("Empty question_text")
        elif norm_text in seen_texts:
            errs.append(f"Duplicate question text: {r['question_id']}")
            report["duplicates_found"] += 1
        seen_texts.add(norm_text)
        
        # Options check
        for opt in ["option_a", "option_b", "option_c", "option_d"]:
            if not r.get(opt) or str(r[opt]).strip() == "":
                errs.append(f"Missing {opt}")
                
        # Correct answer check
        if r.get("correct_answer") not in ["A", "B", "C", "D"]:
            errs.append(f"Invalid correct_answer: {r.get('correct_answer')}")
            
        # Explanation check
        if not r.get("explanation") or len(r["explanation"]) < 10:
            errs.append("Missing or incomplete explanation")
            
        # Difficulty check
        if r.get("difficulty_label") not in ["Easy", "Medium", "Hard"]:
            errs.append(f"Invalid difficulty: {r.get('difficulty_label')}")
            
        # Verification check
        if r.get("verification_status") != "Verified":
            errs.append(f"Unverified record: {r.get('verification_status')}")
            
        if errs:
            report["total_rejected"] += 1
            report["incomplete_records"] += 1
            report["errors"].append({"id": r.get("question_id"), "errors": errs})
        else:
            report["total_accepted"] += 1
            report["verified_records"] += 1
            
        # Distributions
        subj = r.get("subject", "Unknown")
        report["subject_distribution"][subj] = report["subject_distribution"].get(subj, 0) + 1
        diff = r.get("difficulty_label", "Unknown")
        report["difficulty_distribution"][diff] = report["difficulty_distribution"].get(diff, 0) + 1
        ans = r.get("correct_answer", "Unknown")
        report["answer_distribution"][ans] = report["answer_distribution"].get(ans, 0) + 1
        
    if report["errors"]:
        report["validation_checks_passed"] = False
        
    return report

